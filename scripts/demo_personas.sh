#!/usr/bin/env bash
# Demo personas (handoff 46): seed, list or remove them on one tenant.
#
#   scripts/demo_personas.sh <db> seed
#   scripts/demo_personas.sh <db> list
#   scripts/demo_personas.sh <db> remove [--apply]
#
# The only reason this wrapper exists is the passwords. `seed` prints the
# ones it generates between two sentinel lines; this script lifts them into
# docs/api/.personas.<db> (mode 600, gitignored) and prints everything else,
# so a password never reaches the terminal, a log or the repository. The
# owner reads that file to switch profiles; nobody else needs to.
set -euo pipefail

db="${1:?usage: $0 <db> seed|list|remove [--apply]}"
action="${2:?usage: $0 <db> seed|list|remove [--apply]}"
root="$(cd "$(dirname "$0")/.." && pwd)"
compose=(docker compose -f "$root/docker-compose.yml" -f "$root/docker-compose.19.yml")
shell_args=(odoo shell -c /etc/odoo/odoo.conf -d "$db" --no-http
            --http-port=8099 --gevent-port=8098 --log-level=error)

case "$action" in
  list)
    "${compose[@]}" exec -T odoo "${shell_args[@]}" \
      < "$root/scripts/list_demo_personas.py"
    ;;
  remove)
    apply=()
    [[ "${3:-}" == "--apply" ]] && apply=(-e CADRA_APPLY=1)
    "${compose[@]}" exec -T ${apply[@]+"${apply[@]}"} odoo "${shell_args[@]}" \
      < "$root/scripts/remove_demo_personas.py"
    ;;
  seed)
    reset=()
    [[ -n "${CADRA_DEMO_RESET_PASSWORDS:-}" ]] && \
      reset=(-e "CADRA_DEMO_RESET_PASSWORDS=$CADRA_DEMO_RESET_PASSWORDS")
    out="$(mktemp)"; trap 'rm -f "$out"' EXIT; chmod 600 "$out"
    status=0
    "${compose[@]}" exec -T ${reset[@]+"${reset[@]}"} odoo "${shell_args[@]}" \
      < "$root/scripts/seed_demo_personas.py" > "$out" || status=$?
    creds="$root/docs/api/.personas.$db"
    # Everything but the password block goes to the terminal.
    sed '/^CADRA_PERSONAS_BEGIN$/,/^CADRA_PERSONAS_END$/d' "$out"
    # New passwords replace the line for the same persona; others are kept.
    python3 - "$out" "$creds" <<'PY'
import os, sys
out, creds = sys.argv[1], sys.argv[2]
lines, inside = [], False
for line in open(out):
    line = line.rstrip("\n")
    if line == "CADRA_PERSONAS_BEGIN":
        inside = True
    elif line == "CADRA_PERSONAS_END":
        inside = False
    elif inside and line.strip():
        lines.append(line)
if not lines:
    print("passwords  : none new%s" % (" — %s unchanged" % os.path.relpath(creds)
                                      if os.path.exists(creds) else ""))
    sys.exit(0)
known = {}
if os.path.exists(creds):
    for line in open(creds):
        if line.strip() and not line.startswith("#"):
            known[line.split()[0]] = line.rstrip("\n")
for line in lines:
    known[line.split()[0]] = line
fd = os.open(creds, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write("# Demo personas on this tenant (handoff 46): key login password.\n"
            "# Generated by scripts/seed_demo_personas.py. Gitignored; never copy.\n")
    for key in sorted(known):
        f.write(known[key] + "\n")
os.chmod(creds, 0o600)
print("passwords  : %d written to %s (mode 600)" % (len(lines), os.path.relpath(creds)))
PY
    exit "$status"
    ;;
  *)
    echo "unknown action: $action (seed|list|remove)" >&2; exit 64 ;;
esac
